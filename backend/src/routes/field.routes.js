const router = require('express').Router();
const {authenticateToken,requireRole}=require('../middleware/auth.middleware');
const c=require('../controllers/field.controller');
router.param('id',require('../middleware/request.middleware').validateId);
router.use(authenticateToken);
const staff=requireRole(['ADMIN','VOLUNTEER']), admin=requireRole(['ADMIN']);
router.get('/reservations',c.reservations);
router.post('/assets/:id/reservations',staff,c.reserve);
router.patch('/reservations/:id',c.decideReservation);
router.get('/intakes',staff,c.intakes);
router.post('/intakes',staff,c.admit);
router.patch('/intakes/:id/consent',staff,c.consent);
router.patch('/intakes/:id/depart',staff,c.depart);
router.get('/missing/:id/suggestions',staff,c.suggestions);
router.post('/missing/:id/matches',staff,c.match);
router.get('/recovery',c.recoveryList);
router.post('/recovery',c.createRecovery);
router.patch('/recovery/:id',staff,c.updateRecovery);
router.get('/preparedness',c.getPlan);
router.put('/preparedness',c.savePlan);
router.get('/metrics',admin,c.metrics);
router.post('/warning-reviews',admin,c.warningReview);
const routing=require('../controllers/routing.controller');
router.get('/corridors',admin,routing.list);
router.post('/corridors',admin,routing.create);
router.patch('/corridors/:id/close',admin,routing.close);
router.post('/routes',routing.suggest);
const evacuation=require('../controllers/evacuation.controller');
router.get('/evacuation',evacuation.list);
router.post('/evacuation',admin,evacuation.publish);
router.patch('/evacuation/:id/close',admin,evacuation.close);
router.post('/evacuation/plan',evacuation.plan);
router.get('/help-points',evacuation.helpPoints);
router.post('/help-points',admin,evacuation.createPoint);
router.patch('/help-points/:id/check-in',staff,evacuation.checkIn);
router.patch('/help-points/:id/close',admin,evacuation.closePoint);
module.exports=router;
