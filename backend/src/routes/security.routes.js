const router=require('express').Router(),rateLimit=require('express-rate-limit');
const c=require('../controllers/security.controller'),{authenticateToken,requireRole}=require('../middleware/auth.middleware');
const limiter=rateLimit({store:new (require("../services/database-rate-store").DatabaseRateStore)("security"),windowMs:15*60000,limit:10,standardHeaders:true,legacyHeaders:false,message:{error:'Too many security attempts. Retry after 15 minutes.'},skip:req=>process.env.NODE_ENV==='test'&&process.env.DISABLE_RATE_LIMITS==='true'});
router.param('id',require('../middleware/request.middleware').validateId);
router.post('/forgot-password',limiter,c.forgot);
router.post('/reset-password',limiter,c.reset);
router.use(authenticateToken);
router.get('/',c.status);
router.post('/logout',c.logout);
router.post('/mfa/setup',limiter,c.setup);
router.post('/mfa/enable',limiter,c.enable);
router.post('/mfa/disable',limiter,c.disable);
router.post('/password',limiter,c.changePassword);
router.post('/email/request',limiter,c.requestVerification);
router.post('/email/verify',limiter,c.verifyEmail);
router.post('/phone/request',limiter,c.requestPhone);
router.post('/phone/verify',limiter,c.verifyPhone);
router.patch('/responders/:id/review',requireRole(['ADMIN']),c.reviewIdentity);
module.exports=router;
